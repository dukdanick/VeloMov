//! UI translations. English strings are the keys; Portuguese (Brazil) uses
//! the usual vocabulary of Brazilian video editors.

use std::collections::HashMap;
use std::sync::atomic::{AtomicU8, Ordering};
use std::sync::OnceLock;

static LANG: AtomicU8 = AtomicU8::new(0);

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Pt,
}

pub fn set_lang(l: Lang) {
    LANG.store(if l == Lang::Pt { 1 } else { 0 }, Ordering::Relaxed);
}

pub fn lang() -> Lang {
    if LANG.load(Ordering::Relaxed) == 1 {
        Lang::Pt
    } else {
        Lang::En
    }
}

/// Language from the environment (LANG / LC_ALL / LC_MESSAGES).
pub fn system_lang() -> Lang {
    for v in ["LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"] {
        if let Ok(s) = std::env::var(v) {
            if s.is_empty() {
                continue;
            }
            return if s.to_lowercase().starts_with("pt") { Lang::Pt } else { Lang::En };
        }
    }
    Lang::En
}

fn pt() -> &'static HashMap<&'static str, &'static str> {
    static M: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    M.get_or_init(|| PT.iter().copied().collect())
}

/// Translate a UI string.
pub fn tr(s: &str) -> &str {
    if lang() == Lang::Pt {
        if let Some(t) = pt().get(s) {
            return t;
        }
    }
    s
}

